def test_new_chat_and_followups_survive_restart_without_duplicate_messages(tmp_path: Path) -> None:
    path = tmp_path / "support.sqlite3"
    now = [1_700_000_000.0]
    store = SQLiteStore(path, clock=lambda: now[0])
    customer = store.create_customer(plan="Pro", display_name="Yean")
    first = TicketMessage(text="  Payment failed\nwhen upgrading.  ", message_id="first")
    ticket = store.create_ticket(customer.customer_id, first)
    created = store.get_ticket_summary(ticket.ticket_id, customer.customer_id)
    assert created.title == "Payment failed when upgrading."
    assert created.status == "open"
    assert created.message_count == 1
    assert created.created_at == datetime.fromtimestamp(now[0], timezone.utc)
    assert ticket.messages[0].message_id == "first"
    assert ticket.messages[0].observed_at is not None
    assert store.latest_result(ticket.ticket_id, customer.customer_id) is None
    assert store.contains_message(ticket.ticket_id, "first", customer.customer_id)
    assert not store.contains_message(ticket.ticket_id, "not-present", customer.customer_id)

    now[0] += 60
    store.append_message(ticket.ticket_id, customer.customer_id, TicketMessage(text="More detail", message_id="second"))
    updated = store.get_ticket_summary(ticket.ticket_id, customer.customer_id)
    assert updated.created_at == created.created_at
    assert updated.updated_at > created.updated_at
    assert updated.title == created.title
    assert updated.message_count == 2
    now[0] += 60
    store.append_message(ticket.ticket_id, customer.customer_id, TicketMessage(text="More detail", message_id="second"))
    store.ingest_ticket(ticket)
    reopened = SQLiteStore(path, clock=lambda: now[0])
    assert reopened.get_ticket_summary(ticket.ticket_id, customer.customer_id) == updated
    assert [item.text for item in reopened.load_history(ticket.ticket_id, customer.customer_id).messages] == [first.text, "More detail"]
    assert reopened.list_tickets(customer.customer_id) == [updated]


def test_new_ticket_creation_is_atomic_and_rejects_unknown_customers(tmp_path: Path) -> None:
    store = SQLiteStore(tmp_path / "support.sqlite3")
    customer = store.create_customer(plan="Free")
    store.create_ticket(customer.customer_id, TicketMessage(text="Question", message_id="shared-id"))
    with pytest.raises(ValueError, match="Message ID"):
        store.create_ticket(customer.customer_id, TicketMessage(text="Question", message_id="shared-id"))
    with pytest.raises(ValueError, match="blank"):
        store.create_ticket(customer.customer_id, TicketMessage(text=" \n "))
    with pytest.raises(KeyError, match="Customer"):
        store.create_ticket("unknown", TicketMessage(text="Question"))
    assert len(store.list_tickets(customer.customer_id)) == 1
    with sqlite3.connect(store.path) as connection:
        assert connection.execute("SELECT COUNT(*) FROM tickets").fetchone()[0] == 1
        assert connection.execute("SELECT COUNT(*) FROM ticket_messages").fetchone()[0] == 1


def test_summaries_and_latest_results_enforce_ticket_ownership(tmp_path: Path) -> None:
    store = SQLiteStore(tmp_path / "support.sqlite3")
    owner = store.create_customer(plan="Free")
    other = store.create_customer(plan="Pro")
    ticket = store.create_ticket(owner.customer_id, TicketMessage(text="Private question"))
    for operation in [
        lambda: store.get_ticket_summary(ticket.ticket_id, other.customer_id),
        lambda: store.latest_result(ticket.ticket_id, other.customer_id),
        lambda: store.contains_message(ticket.ticket_id, ticket.messages[0].message_id, other.customer_id),
    ]:
        with pytest.raises(ValueError, match="different customer"):
            operation()
    with pytest.raises(KeyError):
        store.list_tickets("unknown")
    with pytest.raises(KeyError):
        store.get_ticket_summary("missing", owner.customer_id)
    assert store.list_tickets(other.customer_id) == []


def test_latest_result_reopens_and_triage_keeps_the_ticket_open(tmp_path: Path) -> None:
    path = tmp_path / "support.sqlite3"
    now = [1_700_000_000.0]
    store = SQLiteStore(path, clock=lambda: now[0])
    customer = store.create_customer(plan="Pro")
    ticket = store.create_ticket(customer.customer_id, TicketMessage(text="Help"))
    created = store.get_ticket_summary(ticket.ticket_id, customer.customer_id)
    now[0] += 30
    store.save_result(result(ticket.ticket_id))
    now[0] += 30
    newest = result(ticket.ticket_id, "frustrated")
    store.save_result(newest)
    reopened = SQLiteStore(path, clock=lambda: now[0])
    summary = reopened.get_ticket_summary(ticket.ticket_id, customer.customer_id)
    assert reopened.latest_result(ticket.ticket_id, customer.customer_id) == newest
    assert summary.status == "open"
    assert summary.created_at == created.created_at
    assert summary.updated_at > created.updated_at
    assert summary.message_count == 1


def test_ticket_list_includes_seeded_and_new_chats_and_updates_activity_order(tmp_path: Path) -> None:
    now = [1_700_000_000.0]
    store = SQLiteStore(tmp_path / "support.sqlite3", clock=lambda: now[0])
    seed(store)
    sample = store.list_tickets("customer-001")[0]
    assert sample.ticket_id == "ticket-001"
    assert sample.message_count == 3
    now[0] += 10
    new_ticket = store.create_ticket("customer-001", TicketMessage(text="A second problem"))
    assert [item.ticket_id for item in store.list_tickets("customer-001")] == [new_ticket.ticket_id, "ticket-001"]
    now[0] += 10
    store.append_message("ticket-001", "customer-001", TicketMessage(text="Still waiting"))
    assert [item.ticket_id for item in store.list_tickets("customer-001")] == ["ticket-001", new_ticket.ticket_id]
    assert store.get_ticket_summary("ticket-001", "customer-001").created_at == sample.created_at


def test_pending_sample_check_and_reseeding_preserve_customized_profiles(tmp_path: Path) -> None:
    path = tmp_path / "support.sqlite3"
    store = SQLiteStore(path)
    seed(store)
    raw = json.loads((FIXTURES / "sample_tickets.json").read_text())[0]
    sample = TicketInput.model_validate(raw)
    latest = sample.messages[-1]
    identifier = stable_message_id(sample.ticket_id, len(sample.messages), latest)
    assert not store.contains_message(sample.ticket_id, identifier, sample.customer_id)
    store.append_message(sample.ticket_id, sample.customer_id, latest.model_copy(update={"message_id": identifier}))
    assert store.contains_message(sample.ticket_id, identifier, sample.customer_id)
    profile = store.get_customer(sample.customer_id)
    assert profile is not None
    changed = profile.model_copy(update={"display_name": "Edited customer", "notes": ["Keep this"]})
    with sqlite3.connect(path) as connection:
        connection.execute("UPDATE customers SET profile_json = ? WHERE customer_id = ?", (changed.model_dump_json(), changed.customer_id))
    reopened = SQLiteStore(path)
    seed(reopened)
    assert reopened.get_customer(sample.customer_id) == changed
    assert reopened.get_ticket_summary(sample.ticket_id, sample.customer_id).message_count == 4


def test_legacy_metadata_migration_retains_profiles_history_and_unknown_observations(tmp_path: Path) -> None:
    path = tmp_path / "legacy.sqlite3"
    profile_json = '{"customer_id":"legacy","plan":"Pro","tenure_months":5,"notes":["Already edited"]}'
    with sqlite3.connect(path) as connection:
        connection.executescript("""
            CREATE TABLE customers (customer_id TEXT PRIMARY KEY, profile_json TEXT NOT NULL);
            CREATE TABLE tickets (ticket_id TEXT PRIMARY KEY, customer_id TEXT NOT NULL);
            CREATE TABLE ticket_messages (
                message_id TEXT PRIMARY KEY, ticket_id TEXT NOT NULL REFERENCES tickets(ticket_id),
                sequence INTEGER NOT NULL, text TEXT NOT NULL, time_label TEXT NOT NULL,
                role TEXT NOT NULL, UNIQUE(ticket_id, sequence)
            );
        """)
        connection.execute("INSERT INTO customers VALUES (?, ?)", ("legacy", profile_json))
        connection.execute("INSERT INTO tickets VALUES (?, ?)", ("legacy-ticket", "legacy"))
        connection.execute("INSERT INTO ticket_messages VALUES (?, ?, ?, ?, ?, ?)", ("original-id", "legacy-ticket", 1, "Original\nquestion", "yesterday", "customer"))
    now = [1_700_000_000.0]
    store = SQLiteStore(path, clock=lambda: now[0])
    first = store.get_ticket_summary("legacy-ticket", "legacy")
    assert first.title == "Original question"
    assert first.status == "open"
    assert first.message_count == 1
    assert first.created_at == datetime.fromtimestamp(now[0], timezone.utc)
    assert store.load_history("legacy-ticket", "legacy").messages[0].observed_at is None
    new = store.create_customer(plan="Free")
    assert [item.customer_id for item in store.list_customers()] == ["legacy", new.customer_id]
    now[0] += 60
    restarted = SQLiteStore(path, clock=lambda: now[0])
    assert restarted.get_ticket_summary("legacy-ticket", "legacy") == first
    with sqlite3.connect(path) as connection:
        assert connection.execute("SELECT profile_json FROM customers WHERE customer_id = 'legacy'").fetchone()[0] == profile_json
        assert connection.execute("SELECT message_id, text, observed_at FROM ticket_messages").fetchall() == [("original-id", "Original\nquestion", None)]
        columns = [row[1] for row in connection.execute("PRAGMA table_info(tickets)")]
        assert all(columns.count(column) == 1 for column in ["title", "status", "created_at", "updated_at"])
