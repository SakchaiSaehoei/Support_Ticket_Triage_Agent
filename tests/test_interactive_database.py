"""Check customer selection and durable chats without credentials or provider calls."""

from datetime import datetime, timezone
import json
from pathlib import Path
import sqlite3

from pydantic import ValidationError
import pytest

from support_ticket_triage.database import SQLiteStore, stable_message_id
from support_ticket_triage.schemas import (
    CustomerProfile,
    ExtractedIssue,
    NextAction,
    TicketAnalysis,
    TicketInput,
    TicketMessage,
    TicketResult,
    TriageDecision,
    Urgency,
)


FIXTURES = Path(__file__).resolve().parents[1] / "data" / "fixtures"


def seed(store: SQLiteStore) -> dict[str, int]:
    return store.seed_samples(
        FIXTURES / "customer_accounts.json", FIXTURES / "sample_tickets.json"
    )


def result(ticket_id: str, sentiment: str = "neutral") -> TicketResult:
    return TicketResult(
        ticket_id=ticket_id,
        analysis=TicketAnalysis(
            product=None, issue_type="usage", customer_sentiment=sentiment,
            issues=[ExtractedIssue(issue_type="usage", description="Needs support")],
        ),
        decision=TriageDecision(urgency=Urgency.LOW, action=NextAction.AUTO_RESPOND),
        reply="This is a saved draft.",
    )


def test_optional_profile_facts_remain_unknown_and_old_fixtures_still_validate() -> None:
    unknown = CustomerProfile(customer_id="new", plan="Free")
    assert unknown.tenure_months is None
    assert unknown.display_name is None
    assert unknown.prior_support_tickets is None
    with pytest.raises(ValidationError):
        CustomerProfile(customer_id="invalid", plan="Free", tenure_months=-1)
    raw = json.loads((FIXTURES / "customer_accounts.json").read_text())
    assert [CustomerProfile.model_validate(item).tenure_months for item in raw.values()] == [4, 8, 5]


def test_customer_order_and_autogenerated_labels_persist_with_seeded_profiles(tmp_path: Path) -> None:
    path = tmp_path / "support.sqlite3"
    store = SQLiteStore(path)
    seed(store)
    existing = store.list_customers()
    assert [item.customer_id for item in existing] == ["customer-001", "customer-002", "customer-003"]
    fourth = store.create_customer(plan="Free")
    named = store.create_customer(plan="Enterprise", display_name="  Acme Thailand  ", seats=12)
    assert fourth.display_name == "Customer 4"
    assert fourth.tenure_months is None
    assert fourth.customer_id not in {item.customer_id for item in existing}
    assert named.customer_id != fourth.customer_id
    assert named.display_name == "Acme Thailand"
    assert named.seats == 12
    reopened = SQLiteStore(path)
    assert reopened.list_customers() == existing + [fourth, named]
    assert reopened.get_customer(fourth.customer_id) == fourth
    assert seed(reopened) == {"customers": 0, "tickets": 0, "messages": 0}
    assert reopened.list_customers() == existing + [fourth, named]


